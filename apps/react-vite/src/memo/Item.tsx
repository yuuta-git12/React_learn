// =============================================================================
// Item コンポーネント
// メモ一覧の各行（1件分のメモ）を表示するコンポーネント
// =============================================================================

/**
 * Item コンポーネント
 * メモの番号、メッセージ内容、作成日時を1行のテーブル行として表示する
 * @param props.value - メモデータ（message, created を含む）
 * @param props.index - 表示用の番号（1始まり）
 */
function Item(props: {value: any, index: number}){
    // -----------------------------------------------------------------------------
    // スタイル定義
    // -----------------------------------------------------------------------------
    // 番号セル（th）のスタイル：左寄せ、幅70px
    const th = {
        textAlign: "left" as const,
        width: "70px"
    }

    // 日時セル（td）のスタイル：右寄せ、幅150px
    const td = {
        textAlign: "right" as const,
        width: "150px"
    }

    // -----------------------------------------------------------------------------
    // 日時のフォーマット処理
    // -----------------------------------------------------------------------------
    // createdプロパティ（ISO文字列）をDateオブジェクトに変換
    let d = new Date(Date.parse(props.value.created));
    // 「月/日 時:分」の形式にフォーマット
    let f = d.getMonth() + '/' + d.getDate() + ' '
        + d.getHours() + ':' + d.getMinutes();

    // -----------------------------------------------------------------------------
    // レンダリング
    // -----------------------------------------------------------------------------
    return (
        <tr><th style={th}>No, {props.index}</th>
            <td>{props.value.message}</td>
            <td style={td}>{f}</td>
        </tr>
    )
}
export default Item;
