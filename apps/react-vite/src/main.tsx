// =============================================================================
// React アプリケーションのエントリーポイント (Vite版)
// =============================================================================

import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import App from './App.tsx'          // メインのAppコンポーネント
import App_hook_state from './App_hook_state.tsx'  // フック・ステート用のApp_hook_stateコンポーネント
import './index.css'                 // グローバルCSSスタイルのインポート
import App_child from './App_child.tsx'            // 子コンポーネントサンプル用のApp_childコンポーネント
import App_bidirectionl from './App_bidirectional.tsx'  // 双方向データバインディングサンプル用コンポーネント

// -----------------------------------------------------------------------------
// ルート要素の取得と検証
// -----------------------------------------------------------------------------
// index.html内の<div id="root">要素を取得
const rootElement = document.getElementById('root')

// ルート要素が存在しない場合はエラーをスロー（TypeScriptの型安全性も確保）
if (!rootElement) {
  throw new Error('Root container missing in index.html')
}

// -----------------------------------------------------------------------------
// Reactルートの作成
// -----------------------------------------------------------------------------
// createRoot: React 18で導入された新しいルートAPI
// 注意: createRootは一度だけ呼び出し、同じrootインスタンスを再利用する
const root = createRoot(rootElement)

// -----------------------------------------------------------------------------
// カウンター状態の管理
// -----------------------------------------------------------------------------
// 注意: 通常はuseStateフックを使用するが、ここでは手動での再レンダリングを学習するため
//       グローバル変数として定義している
var counter = 0;

// -----------------------------------------------------------------------------
// クリックイベントハンドラ
// -----------------------------------------------------------------------------
// カウンターをインクリメントし、画面を再レンダリングする
const doAction = () =>{
  counter++;  // カウンターを1増加
  render();   // 手動で再レンダリングを実行
}

// -----------------------------------------------------------------------------
// レンダリング関数
// -----------------------------------------------------------------------------
// Appコンポーネントをルート要素にレンダリングする
// - StrictMode: 開発時に潜在的な問題を検出するためのラッパー
// - counter: 現在のカウンター値をpropsとしてAppに渡す
// - onClick: クリック時のコールバック関数をpropsとしてAppに渡す
function render(){
  root.render(
    <StrictMode>
      <App counter={counter} onClick={doAction}/>
      <App_hook_state />
      <App_child />  {/* 子コンポーネントサンプル */}
      <App_bidirectionl />
    </StrictMode>,
  )
}

// -----------------------------------------------------------------------------
// 初回レンダリングの実行
// -----------------------------------------------------------------------------
render();

